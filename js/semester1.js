// Buka/tutup satu folder matkul
function toggleAccordion(id) {
    const content = document.getElementById(id);
    const icon = document.getElementById(`icon-${id}`);
    if (!content) return;

    const opening = content.classList.contains('hidden');
    content.classList.toggle('hidden', !opening);
    if (icon) icon.innerHTML = `<i class="fa-solid fa-chevron-${opening ? 'up' : 'down'}"></i>`;
}

function toggleAllAccordions(open) {
    for (let i = 1; i <= 6; i++) {
        const content = document.getElementById(`acc-m${i}`);
        const icon = document.getElementById(`icon-acc-m${i}`);
        if (!content) continue;
        content.classList.toggle('hidden', !open);
        if (icon) icon.innerHTML = `<i class="fa-solid fa-chevron-${open ? 'up' : 'down'}"></i>`;
    }
}

// Cari matkul
function filterSem1Courses() {
    const query = (document.getElementById('search-sem1-input')?.value || '').toLowerCase();
    document.querySelectorAll('.sem1-card').forEach(card => {
        const keywords = (card.getAttribute('data-keywords') || '').toLowerCase();
        card.classList.toggle('hidden', !keywords.includes(query));
    });
}

